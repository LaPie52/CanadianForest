-- À exécuter dans Supabase > SQL Editor.
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(nickname) between 1 and 18),
  score integer not null check (score between -20000 and 30000),
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;

-- Tout le monde peut consulter les dix meilleurs scores.
drop policy if exists "Scores publics lisibles" on public.scores;
create policy "Scores publics lisibles"
on public.scores for select
to anon, authenticated
using (true);

-- Le jeu peut envoyer un score avec la clé publique anon.
drop policy if exists "Scores publics ajoutables" on public.scores;
create policy "Scores publics ajoutables"
on public.scores for insert
to anon, authenticated
with check (
  char_length(nickname) between 1 and 18
  and score between -20000 and 30000
);

grant select, insert on public.scores to anon, authenticated;
grant usage, select on sequence public.scores_id_seq to anon, authenticated;

-- Index pour accélérer l'affichage du classement.
create index if not exists scores_leaderboard_idx
on public.scores (score desc, created_at asc);
